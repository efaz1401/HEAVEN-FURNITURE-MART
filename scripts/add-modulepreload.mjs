/* Emit <link rel="modulepreload"> for each page's real module graph.
 *
 * ES modules are discovered a level at a time: the parser finds the entry point,
 * fetches it, parses it, and only then learns what it imports. Measured on a
 * piece page at 150ms RTT, that is four sequential waves —
 *
 *     0-1286ms  chrome.js, piece-fill.js, piece.js, configurator.js
 *  1038-1486ms    data/pieces.js
 *  1250-1558ms      card.js, order.js, pricing.js
 *  1501-1852ms        shell.js, magnetic.js, menu.js
 *
 * — roughly 450-600ms of pure latency. The graph is entirely static, so the
 * browser can be told about it up front and fetch the whole thing in parallel.
 *
 * WHAT IS AND IS NOT PRELOADED
 *   - entry points are NOT preloaded: the preload scanner already finds their
 *     <script src> tags while parsing the head. Only their dependencies gain
 *     anything, and preloading an entry twice just adds a duplicate warning.
 *   - chrome.js's four dynamic imports ARE preloaded. They are unconditional —
 *     the module ends with import('./shell.js') and three more — so they are part
 *     of every page's real graph despite being dynamic.
 *   - absolute URLs are NEVER preloaded. model-viewer is 252 KB fetched only when
 *     someone taps "View in 3D"; preloading it would undo the whole point of
 *     loading it on demand.
 *
 *     node scripts/add-modulepreload.mjs [--check]
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, resolve, posix } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const SKIP = new Set(['dist', '_ref', 'node_modules', 'scripts', 'tests']);

/* Static imports plus the unconditional dynamic ones. A dynamic import inside a
   function body is lazy and deliberately not matched. */
const STATIC_IMPORT = /^\s*import\s+(?:[\s\S]*?\sfrom\s+)?['"]([^'"]+)['"]/gm;
const TOP_DYNAMIC = /^import\(['"]([^'"]+)['"]\)/gm;

function depsOf(file) {
  const src = readFileSync(file, 'utf8');
  const out = [];
  for (const re of [STATIC_IMPORT, TOP_DYNAMIC]) {
    re.lastIndex = 0;
    for (let m = re.exec(src); m; m = re.exec(src)) {
      if (!/^[./]/.test(m[1])) continue;                 // bare or absolute URL
      const target = resolve(dirname(file), m[1]);
      if (existsSync(target)) out.push(target);
    }
  }
  return out;
}

function graph(entries) {
  const seen = new Set(entries);
  const deps = new Set();
  const queue = [...entries];
  while (queue.length) {
    for (const d of depsOf(queue.shift())) {
      if (seen.has(d)) continue;
      seen.add(d);
      deps.add(d);
      queue.push(d);
    }
  }
  return deps;
}

function htmlFiles(dir = ROOT, acc = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (!SKIP.has(e.name) && !e.name.startsWith('.')) htmlFiles(join(dir, e.name), acc);
    } else if (e.name.endsWith('.html')) {
      acc.push(join(dir, e.name));
    }
  }
  return acc;
}

const MARKER_OPEN = '<!-- modulepreload: generated by scripts/add-modulepreload.mjs -->';
const MARKER_CLOSE = '<!-- /modulepreload -->';
/* TWO BUGS, ONE LINE, AND THEY COMPOUNDED.

   This regex was `...${MARKER_CLOSE}\\n` with no flags, and the pages on disk
   are CRLF — so the close marker is followed by \r\n and the pattern never
   matched a real block at all. The strip on the next line was a no-op, every
   run appended one more block, and all 23 shipped pages ended up carrying
   their preload hints two and three times over.

   \r?\n makes it match the file as it actually is; the g flag makes it strip
   EVERY block rather than the first, which is what "idempotent" needs once a
   page has already accumulated more than one. Neither fix works alone. */
const BLOCK = new RegExp(`[ \\t]*${MARKER_OPEN}[\\s\\S]*?${MARKER_CLOSE}\\r?\\n`, 'g');

let changed = 0;
for (const page of htmlFiles().sort()) {
  let text = readFileSync(page, 'utf8');
  text = text.replace(BLOCK, '');                        // idempotent

  const entries = [...text.matchAll(/<script type="module" src="([^"]+)"/g)]
    .map((m) => resolve(dirname(page), m[1])).filter(existsSync);
  if (!entries.length) { if (check) console.log(`no modules   ${relative(ROOT, page)}`); continue; }

  /* collections/index.html keeps its logic in an inline module; its imports have
     to be read from the page itself. */
  const inline = [...text.matchAll(/import\s+\{[^}]*\}\s+from\s+'([^']+)'/g)]
    .map((m) => resolve(dirname(page), m[1])).filter(existsSync);

  const deps = graph([...entries, ...inline]);
  for (const i of inline) deps.add(i);                   // inline entry has no <script src>
  if (!deps.size) continue;

  const prefix = posix.dirname(relative(ROOT, page).split('\\').join('/'));
  const href = (f) => posix.relative(prefix === '.' ? '' : prefix,
    relative(ROOT, f).split('\\').join('/')) || relative(ROOT, f);

  const links = [...deps].map(href).sort()
    .map((h) => `<link rel="modulepreload" href="${h}">`);
  /* Match the page's own line endings. These files are CRLF; emitting \n here
     would leave one LF-terminated island inside an otherwise CRLF document and
     make every future diff of this block noise. */
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const indent = '';
  const blockText = `${indent}${MARKER_OPEN}${eol}`
    + links.map((l) => indent + l).join(eol) + `${eol}${indent}${MARKER_CLOSE}${eol}`;

  const anchor = '</head>';
  if (!text.includes(anchor)) throw new Error(`no </head> in ${page}`);
  const next = text.replace(anchor, blockText + anchor);
  changed += 1;
  console.log(`${check ? 'would add' : 'added'} ${String(links.length).padStart(2)} preloads  ${relative(ROOT, page)}`);
  if (!check) writeFileSync(page, next, 'utf8');
}
console.log(`\n${changed} pages`);
process.exit(check && changed ? 1 : 0);
